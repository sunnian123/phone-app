# -*- coding: utf-8 -*-
"""
phone.dat 离线手机号归属地解析器
数据库格式：
  - 前4字节：版本号(int32小端)
  - 4-8字节：索引区起始偏移(int32小端)
  - 索引区：每条7字节 = 4字节号段(int32) + 3字节数据偏移(uint24小端)
  - 数据区：以\0结尾的字符串，格式 "运营商|省份|城市|邮编|区号"
"""
import struct
import os


class 手机号归属地解析器:
    def __init__(self, 数据库路径):
        self.数据库路径 = 数据库路径
        self.数据 = None
        self.索引起始 = 0
        self.索引条数 = 0
        self.版本号 = 0
        self.加载()

    def 加载(self):
        if not os.path.exists(self.数据库路径):
            raise FileNotFoundError(f"数据库文件不存在: {self.数据库路径}")
        with open(self.数据库路径, "rb") as f:
            self.数据 = f.read()
        # 版本号：4字节ASCII，如"2302"表示2023年2月
        self.版本号 = self.数据[0:4].decode("ascii", errors="replace")
        # 索引区起始偏移：int32小端
        self.索引起始 = struct.unpack_from("<I", self.数据, 4)[0]
        # 每条索引9字节 = 4字节号段 + 4字节数据偏移 + 1字节类型
        self.索引条数 = (len(self.数据) - self.索引起始) // 9

    def 查询(self, 手机号):
        """查询手机号归属地，返回字典：{'运营商':'','省份':'','城市':'','邮编':'','区号':''}"""
        if not 手机号 or len(手机号) < 7:
            return None
        # 取前7位
        号段 = int(手机号[:7])
        # 二分查找索引区（每条9字节）
        左 = 0
        右 = self.索引条数 - 1
        命中索引 = None
        while 左 <= 右:
            中 = (左 + 右) // 2
            偏移 = self.索引起始 + 中 * 9
            当前号段 = struct.unpack_from("<I", self.数据, 偏移)[0]
            if 当前号段 == 号段:
                命中索引 = 中
                break
            elif 当前号段 < 号段:
                左 = 中 + 1
            else:
                右 = 中 - 1

        if 命中索引 is None:
            return None

        # 读取4字节数据偏移（int32小端），+1字节类型
        索引偏移 = self.索引起始 + 命中索引 * 9 + 4
        数据偏移 = struct.unpack_from("<I", self.数据, 索引偏移)[0]
        运营商类型 = self.数据[索引偏移 + 4]

        # 从数据偏移读取到\0
        结束 = self.数据.find(b"\x00", 数据偏移)
        if 结束 == -1:
            原始字符串 = self.数据[数据偏移:].decode("utf-8", errors="replace")
        else:
            原始字符串 = self.数据[数据偏移:结束].decode("utf-8", errors="replace")

        # 解析格式：省份|城市|邮编|区号
        字段 = 原始字符串.split("|")
        运营商映射 = {1: "中国移动", 2: "中国联通", 3: "中国电信", 4: "虚拟运营商",
                     5: "中国移动", 6: "中国联通", 7: "中国广电", 8: "中国电信"}
        运营商 = 运营商映射.get(运营商类型, f"类型{运营商类型}")
        结果 = {
            "运营商": 运营商,
            "省份": 字段[0] if len(字段) > 0 else "",
            "城市": 字段[1] if len(字段) > 1 else "",
            "邮编": 字段[2] if len(字段) > 2 else "",
            "区号": 字段[3] if len(字段) > 3 else "",
            "原始": 原始字符串
        }
        return 结果


